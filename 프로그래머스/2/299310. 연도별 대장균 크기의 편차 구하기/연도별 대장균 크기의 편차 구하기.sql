SELECT SUBSTR(e.DIFFERENTIATION_DATE, 1, 4) + 0 AS YEAR,
    (
        SELECT MAX(f.SIZE_OF_COLONY)
        FROM ECOLI_DATA f
        WHERE SUBSTR(f.DIFFERENTIATION_DATE, 1, 4)
            = SUBSTR(e.DIFFERENTIATION_DATE, 1, 4)
    ) - e.SIZE_OF_COLONY AS YEAR_DEV,
    e.ID
FROM ECOLI_DATA e
ORDER BY YEAR ASC, YEAR_DEV ASC;